namespace PlugLauncher.Platform.MacOs;

/// <summary>
/// نام کلید به کد مجازی مک (<c>kVK_*</c> در HIToolbox).
///
/// برخلاف ویندوز اینجا هیچ الگویی نیست که بشود حسابش کرد: کد <c>A</c> صفر است، <c>B</c> یازده،
/// و اعداد ردیف بالا هم پشت سر هم نیستند. جدول از چیدمان کیبورد اصلی مکینتاش می‌آید و تنها راهش
/// همین شمردنِ تک‌تک است.
///
/// نتیجه با <c>bool</c> برمی‌گردد نه با «صفر یعنی نشد»، چون صفر خودش یک کد معتبر است.
///
/// نام‌های ویندوزی («Space»، «D1»، «Oem3») هم پذیرفته می‌شوند: هات‌کیِ داخل <c>settings.json</c>
/// ممکن است روی ویندوز نوشته شده باشد و همان فایل روی مک هم خوانده می‌شود.
/// </summary>
internal static class MacKeys
{
    private static readonly Dictionary<string, uint> Codes = new(StringComparer.OrdinalIgnoreCase)
    {
        ["a"] = 0x00, ["b"] = 0x0B, ["c"] = 0x08, ["d"] = 0x02, ["e"] = 0x0E, ["f"] = 0x03,
        ["g"] = 0x05, ["h"] = 0x04, ["i"] = 0x22, ["j"] = 0x26, ["k"] = 0x28, ["l"] = 0x25,
        ["m"] = 0x2E, ["n"] = 0x2D, ["o"] = 0x1F, ["p"] = 0x23, ["q"] = 0x0C, ["r"] = 0x0F,
        ["s"] = 0x01, ["t"] = 0x11, ["u"] = 0x20, ["v"] = 0x09, ["w"] = 0x0D, ["x"] = 0x07,
        ["y"] = 0x10, ["z"] = 0x06,

        ["0"] = 0x1D, ["1"] = 0x12, ["2"] = 0x13, ["3"] = 0x14, ["4"] = 0x15,
        ["5"] = 0x17, ["6"] = 0x16, ["7"] = 0x1A, ["8"] = 0x1C, ["9"] = 0x19,

        // املای WPF برای همان ردیف اعداد
        ["d0"] = 0x1D, ["d1"] = 0x12, ["d2"] = 0x13, ["d3"] = 0x14, ["d4"] = 0x15,
        ["d5"] = 0x17, ["d6"] = 0x16, ["d7"] = 0x1A, ["d8"] = 0x1C, ["d9"] = 0x19,

        ["f1"] = 0x7A, ["f2"] = 0x78, ["f3"] = 0x63, ["f4"] = 0x76, ["f5"] = 0x60,
        ["f6"] = 0x61, ["f7"] = 0x62, ["f8"] = 0x64, ["f9"] = 0x65, ["f10"] = 0x6D,
        ["f11"] = 0x67, ["f12"] = 0x6F, ["f13"] = 0x69, ["f14"] = 0x6B, ["f15"] = 0x71,
        ["f16"] = 0x6A, ["f17"] = 0x40, ["f18"] = 0x4F, ["f19"] = 0x50, ["f20"] = 0x5A,

        ["space"] = 0x31,
        ["enter"] = 0x24, ["return"] = 0x24,
        ["tab"] = 0x30,
        ["escape"] = 0x35, ["esc"] = 0x35,

        // کلیدی که روی مک «Delete» نوشته شده همان بک‌اسپیس است؛ اسمِ ذخیره‌شده معنی را نگه
        // می‌دارد نه برچسب روی کلید را، پس هرکدام به همان کاری می‌رود که واقعاً می‌کند
        ["back"] = 0x33, ["backspace"] = 0x33,
        ["delete"] = 0x75, ["del"] = 0x75,

        ["insert"] = 0x72,
        ["home"] = 0x73, ["end"] = 0x77,
        ["pageup"] = 0x74, ["prior"] = 0x74,
        ["pagedown"] = 0x79, ["next"] = 0x79,
        ["left"] = 0x7B, ["right"] = 0x7C, ["down"] = 0x7D, ["up"] = 0x7E,
        ["capslock"] = 0x39,

        // کلیدهای علامت‌دار: هم با اسم WPF، هم با خود علامت
        ["oem3"] = 0x32, ["`"] = 0x32, ["backquote"] = 0x32, ["tilde"] = 0x32,
        ["oemminus"] = 0x1B, ["-"] = 0x1B, ["minus"] = 0x1B,
        ["oemplus"] = 0x18, ["="] = 0x18, ["equals"] = 0x18,
        ["oem4"] = 0x21, ["["] = 0x21,
        ["oem6"] = 0x1E, ["]"] = 0x1E,
        ["oem5"] = 0x2A, ["\\"] = 0x2A,
        ["oem1"] = 0x29, [";"] = 0x29,
        ["oem7"] = 0x27, ["'"] = 0x27,
        ["oemcomma"] = 0x2B, [","] = 0x2B,
        ["oemperiod"] = 0x2F, ["."] = 0x2F,
        ["oem2"] = 0x2C, ["/"] = 0x2C

        // NumLock و PrintScreen و Pause عمداً نیستند: مک چنین کلیدهایی ندارد و ثبت‌نشدنشان
        // باید همان‌جا با یک جمله‌ی روشن معلوم شود، نه با کدی که به کلید دیگری می‌خورد
    };

    public static bool TryKeyCode(string name, out uint keyCode)
    {
        keyCode = 0;
        return !string.IsNullOrWhiteSpace(name) && Codes.TryGetValue(name.Trim(), out keyCode);
    }
}
